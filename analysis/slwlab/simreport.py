"""Render the SIMULATION results (sim/results/*.json) as docs/SIMULATION.md and derive the
pre-registered design numbers (N, windows per validator x arm, spend).

``python -m slwlab.simreport --sim sim/results/sim_v1.json --out ../docs/SIMULATION.md``
"""

from __future__ import annotations

import argparse
import json
import pathlib

BUDGET_LAMPORTS = 38_000_000  # confirmatory budget (limits.rs)
SPENDABLE = 0.9  # 10% kept for funding/sweep fees and over-reservation
# Campaign layout: 3 required strata x 2 validators x 5 arms + 5 upside validators x 2 arms (P, C).
CELLS = 3 * 2 * 5 + 5 * 2
MAIN = [("agave", a, "R_RATIO_AGAVE") for a in "PRC"] + [("fd2", a, "R_RATIO_FD") for a in "PRC"]
WS = [10, 20, 30, 50]


def f2(x):
    return "–" if x is None else f"{x:.2f}"


def fpr(sim: dict, arm: str, n: int, w: int) -> float | None:
    """Exact-test FPR where computed (W <= 20), else the normal approximation."""
    return sim["fpr_exact"].get(f"{arm}/N{n}/W{w}", sim["fpr"].get(f"{arm}/N{n}/W{w}"))


def design_options(sim: dict) -> list[dict]:
    out = []
    for n in (6, 8, 10):
        cost = sim["spend_per_window_lamports"][str(n)]["mean"]
        attempted = int(SPENDABLE * BUDGET_LAMPORTS // cost)
        usable = attempted * sim["usable_rate"][str(n)]["medium"]
        w_cell = usable / CELLS
        grid = [w for w in WS if w <= w_cell]
        w = grid[-1] if grid else None

        def worst(field):
            if w is None:
                return 0.0
            return min(sim["cells"][f"{f}/{a}/{r}/N{n}/W{w}"][field] for f, a, r in MAIN)

        out.append({"n": n, "cost": cost, "attempted": attempted, "usable": usable, "w_cell": w_cell, "w": w,
                    "power_exact_min": worst("power_exact"), "power_half_min": worst("power_half"),
                    "fpr_max": max(fpr(sim, a, n, w) for a in ("P", "R", "C", "X", "F")) if w else None})
    return out


def design_choice(sim: dict) -> dict:
    """Pre-registered rule: among N in {6, 8, 10}, the one whose affordable W (budget, medium
    landing, CELLS cells) gives the highest worst-case power for a half-strength rule over the
    main cells (Agave and Firedancer; arms P, R, C; their own priority rule), provided the
    exact rule is detected with >= 95% power there. Ties go to the cheaper N."""
    opts = [o for o in design_options(sim) if o["w"] and o["power_exact_min"] >= 0.95]
    if not opts:
        return {"n": None, "w": None, "note": "no N meets the exact-rule power requirement"}
    best = max(opts, key=lambda o: (round(o["power_half_min"], 2), -o["cost"]))
    return {"n": best["n"], "w": best["w"], "w_cell": best["w_cell"]}


def render(sim: dict) -> str:
    ch = design_choice(sim)
    n, w = ch["n"], ch["w"]
    out = [
        "# SIMULATION results",
        "",
        "> **SIMULATION**: every number on this page comes from the simulator",
        "> (`analysis/slwlab/sim.py`, `power.py`), not from measurements. Generated by",
        f"> `python -m slwlab.simreport` from `analysis/sim/results/sim_v1.json` (seed {sim['seed']},",
        f"> {sim['reps']} replications per cell). Models and their source references: `sim.py`, VERIFIED_FACTS F6c.",
        "> **Provisional (pre-calibration, preset nuisance levels).** Re-derived after calibration",
        "> with order-agnostic nuisance estimates, then frozen as `prereg-v1` (PREREGISTRATION §0).",
        "",
        "## Design choice (fills PREREGISTRATION §8)",
        "",
        f"Layout: {CELLS} validator x arm cells (3 required strata x 2 validators x 5 arms, plus 5 upside",
        f"validators x arms P and C). {int(SPENDABLE * 100)}% of the {BUDGET_LAMPORTS:,} lamport budget is spendable.",
        "Usable rate = P(at least ceil(0.75 N) of N txs land) at the medium landing probability.",
        "Power is the worst case over the main cells (Agave and Firedancer models, arms P, R, C, their",
        "own priority rule). FPR is the worst arm under the null (exact test where W ≤ 20).",
        "",
        "| N | lamports/window | windows affordable | usable | usable per cell | simulated W used | power, exact rule | power, half-strength rule | max FPR |",
        "|---|---|---|---|---|---|---|---|---|",
        *[f"| {o['n']} | {o['cost']:,.0f} | {o['attempted']} | {o['usable']:.0f} | {o['w_cell']:.1f} | {o['w']} | "
          f"{f2(o['power_exact_min'])} | {f2(o['power_half_min'])} | {f2(o['fpr_max'])} |" for o in design_options(sim)],
        "",
        f"- **Chosen: N = {n}.** (Equal-W view: ≈ {ch.get('w_cell', 0):.0f} usable windows per cell. W is now allocated per cell by power, see the allocation section below.)",
        "- Selection rule: the N whose affordable W gives the highest worst-case power for a half-strength",
        "  rule (each window follows the rule with probability 0.5, otherwise random), provided the exact",
        "  rule is detected with ≥ 95% power. Ties go to the cheaper N.",
        "- NO_RULE needs ≥ 90% half-strength power at the achieved W (§7). Otherwise the verdict is INCONCLUSIVE.",
        "",
        "## tau ceilings: mean tau of rule R under \"R + the family's interleaving\"",
        "",
        f"Medium / low / high nuisance. Cells under {sim['min_ceiling']} (medium) are **not identifiable**:",
        "the arm cannot reveal that rule, and it can never be STRICT there.",
        "",
        "| family | arm | rule | medium | low | high | identifiable |",
        "|---|---|---|---|---|---|---|",
    ]
    for fam, arms in sim["ceilings"].items():
        for arm, rr in arms.items():
            for rule, lv in rr.items():
                med = lv["medium"]["mean_tau"]
                out.append(f"| {fam} | {arm} | {rule} | {f2(med)} | {f2(lv['low']['mean_tau'])} | "
                           f"{f2(lv['high']['mean_tau'])} | {'yes' if med >= sim['min_ceiling'] else 'no'} |")
    out += ["", f"## Power and STRICT thresholds at N = {n}, W = {w}", "",
            "Thresholds are 5th percentiles under the exact model of the cell. STRICT also requires the",
            "rule to be significant after Holm (one-sided α = 0.05).", "",
            "| cell | ceiling | power exact | power half | STRICT: mean tau_norm ≥ | CI lower ≥ | share of windows tau_norm ≥ 0.5 ≥ | P(STRICT) exact | P(STRICT) half |",
            "|---|---|---|---|---|---|---|---|---|"]
    for key in sorted(k for k in sim["cells"] if k.endswith(f"/N{n}/W{w}")):
        c = sim["cells"][key]
        t = c["thresholds"]
        out.append(f"| {key.rsplit('/', 2)[0]} | {f2(c['ceiling'])} | {f2(c['power_exact'])} | {f2(c['power_half'])} | "
                   f"{t['strict_mean']} | {t['strict_ci_lower']} | {t['strict_window_share']} | "
                   f"{f2(c['p_strict_exact'])} | {f2(c['p_strict_half'])} |")
    out += ["", f"Power of the main cells across W (N = {n}, half-strength rule):", "",
            "| cell | " + " | ".join(f"W={x}" for x in WS) + " |", "|---|" + "---|" * len(WS)]
    for f, a, r in MAIN:
        out.append(f"| {f}/{a}/{r} | " + " | ".join(f2(sim['cells'][f'{f}/{a}/{r}/N{n}/W{x}']['power_half']) for x in WS) + " |")
    out += ["", f"## False-positive rate under the null (random order), N = {n}", "",
            "| arm | " + " | ".join(f"W={x}" for x in WS) + " | exact test, W=10 | exact test, W=20 |",
            "|---|" + "---|" * (len(WS) + 2)]
    for arm in ("P", "X", "R", "C", "F"):
        out.append(f"| {arm} | " + " | ".join(f2(sim['fpr'].get(f'{arm}/N{n}/W{x}')) for x in WS) + " | "
                   + " | ".join(f2(sim['fpr_exact'].get(f'{arm}/N{n}/W{x}')) for x in (10, 20)) + " |")
    out += ["", f"## Arm F (exact ties), N = {n}: P(tie rule significant after Holm)", "",
            "Firedancer model: LIFO by arrival at pack (F6b). Agave model: unobservable Slab index (TIE_NONE).", "",
            "| model | W | TIE_ARRIVAL_FIFO | TIE_ARRIVAL_LIFO | TIE_SIGNATURE | TIE_PAYER |", "|---|---|---|---|---|---|"]
    for fam in ("fd2", "agave"):
        for x in WS:
            r = sim["arm_f"][f"{fam}/N{n}/W{x}"]
            out.append(f"| {fam} | {x} | {f2(r['TIE_ARRIVAL_FIFO'])} | {f2(r['TIE_ARRIVAL_LIFO'])} | "
                       f"{f2(r['TIE_SIGNATURE'])} | {f2(r['TIE_PAYER'])} |")
    out += ["", "## Arm X gap response (N = 8): mean tau of R_PRICE / R_FIFO per send gap", "",
            "The gap at which R_PRICE turns negative estimates the scheduler's batching granularity.", "",
            "| model | " + " | ".join(f"gap {g} ms" for g in sorted(sim["x_curve"]["agave"], key=int)) + " |",
            "|---|" + "---|" * len(sim["x_curve"]["agave"])]
    for fam, cur in sim["x_curve"].items():
        out.append(f"| {fam} | " + " | ".join(f"{f2(cur[g]['R_PRICE'])} / {f2(cur[g]['R_FIFO'])}"
                                             for g in sorted(cur, key=int)) + " |")
    pc = sim["positive_control"].get(f"N{n}/W{w}", {})
    out += ["", f"## Positive control (vanilla Agave, R_RATIO_AGAVE, Arm P, N = {n}, W = {w})", "",
            "95% predictive interval of the mean raw tau over W windows:", ""]
    for lvl in ("low", "medium", "high"):
        out.append(f"- {lvl} nuisance: [{f2(pc[lvl][0])}, {f2(pc[lvl][1])}]")
    out += [f"- **registered interval (union over nuisance levels): [{f2(pc['union'][0])}, {f2(pc['union'][1])}]**",
            "  The control passes if the observed mean tau lies inside it. Other (N, W): see the JSON.",
            "", "## Nuisance grid", "", "```json", json.dumps(sim["nuisance"], indent=1), "```", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sim", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    sim = json.loads(pathlib.Path(a.sim).read_text(encoding="utf-8"))
    text = render(sim)
    alloc = pathlib.Path(a.sim).with_name(pathlib.Path(a.sim).name.replace("sim_", "alloc_")).with_suffix(".json")
    if alloc.exists():
        from . import allocate

        text += "\n" + allocate.render(json.loads(alloc.read_text(encoding="utf-8"))) + "\n"
    pathlib.Path(a.out).write_text(text, encoding="utf-8")
    print(json.dumps(design_choice(sim)))


if __name__ == "__main__":
    main()
