#!/usr/bin/env python3
"""POST-HOC, EXPLORATORY: Arm X by send gap, and the Agave Arm C positive-control windows by run.

Written after the confirmatory results had been seen (2026-11-03). It is NOT part of the preregistered
analysis, produces no verdict, and does not change one. It only splits cells the registered analysis pools:

  1. Arm X (priority fee anti-aligned with the send order) by validator stratum and send gap. The registered
     X verdicts pool the gaps 0/10/25/60/120 ms; this shows how the tau of R_PRICE and R_FIFO moves with the gap.
  2. The Agave Arm C windows behind the failed positive control (PREREGISTRATION section 7), per run.

Windows are classified exactly as the registered command classifies them (the same stored getBlocks lists, the
same usable test), and tau is the registered per-window Kendall tau (analysis/slwlab/analyze.py `window_scores`).
Cells are small (a handful to ~15 windows) and windows of one validator are not independent, so the intervals
are descriptive (bootstrap over windows, seeded), not tests.

    python scripts/exploratory_gap_table.py            # write docs/EXPLORATORY_GAP_TABLE.md
    python scripts/exploratory_gap_table.py --check    # exit 1 if the file differs from a regeneration

Deterministic: no wall-clock values, seeded bootstrap, sorted rows, LF output.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))

from slwlab import analyze, blocklist, parse, stats  # noqa: E402

SEED = 20261103
OUT = ROOT / "docs" / "EXPLORATORY_GAP_TABLE.md"
FOOTER = "<!-- sha256: "
STRONG = 0.5  # a window counts as ordered by a rule when its tau with that rule is at least this


def summarize(taus: list[float], seed: int = SEED) -> dict:
    """n, mean, bootstrap 95% interval over windows, and the share of windows with tau >= STRONG / <= -STRONG."""
    v = np.asarray(taus, dtype=float)
    v = v[~np.isnan(v)]
    if len(v) == 0:
        return {"n": 0, "mean": None, "ci": (None, None), "share_pos": None, "share_neg": None}
    lo, hi = stats.bootstrap_ci(v, np.random.default_rng(seed))
    return {"n": int(len(v)), "mean": float(v.mean()), "ci": (lo, hi),
            "share_pos": float((v >= STRONG).mean()), "share_neg": float((v <= -STRONG).mean())}


def f(x, nd=2) -> str:
    return "–" if x is None else f"{x:+.{nd}f}"


def pct(x) -> str:
    return "–" if x is None else f"{100 * x:.0f}%"


def table(head: list[str], rows: list[list]) -> list[str]:
    return (["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
            + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def load_windows(root: pathlib.Path) -> list:
    lines = parse.read_jsonl(root / "data" / "manifest.jsonl")
    data = root / "data"
    needed = blocklist.runs_with_purpose(lines, "measure")
    missing = [r for r in needed if blocklist.load(data, r) is None]
    if missing:
        raise SystemExit("no stored getBlocks list for run(s) " + ", ".join(missing))
    present = blocklist.present_map(data, sorted({l["tx"]["run_id"] for l in lines}))
    return parse.windows_from_manifest(lines, present, False, bool(needed))


def render(root: pathlib.Path) -> str:
    wins = load_windows(root)
    by_gap: dict[tuple[str, int], list[float]] = {}
    sent_gap: dict[tuple[str, int], list[int]] = {}
    for w in wins:
        if w.arm != "X":
            continue
        k = (w.stratum, round(w.gap_us / 1000))
        s = sent_gap.setdefault(k, [0, 0])
        s[0] += 1
        if w.usable:
            s[1] += 1
            by_gap.setdefault(k, []).append(analyze.window_scores(w, ["R_PRICE"])["R_PRICE"][1])
    gaps = sorted({k[1] for k in sent_gap})
    strata = sorted({k[0] for k in sent_gap})

    out = ["# Exploratory, post-hoc: Arm X by send gap, and the Agave Arm C windows", "",
           "> **EXPLORATORY, POST-HOC.** Written on 2026-11-03 after the confirmatory results had been seen. Not part of",
           "> the preregistered analysis; it gives no verdict and changes none. It splits cells that the registered",
           "> analysis pools. Generated by `python scripts/exploratory_gap_table.py` from `data/` (`--check` regenerates",
           "> and compares). Cells are small and windows of one validator are not independent: the intervals are",
           "> descriptive (bootstrap over windows, seed " + str(SEED) + "), not tests.", ""]

    out += ["## 1. Arm X: tau of R_PRICE by send gap", "",
            "Arm X sends the transactions in the reverse order of their priority fee, `gap` apart. A window's tau with",
            "R_PRICE is +1 if the block orders it by fee, -1 if it orders it by send order (in Arm X the tau with R_FIFO",
            "is the same number with the opposite sign). `usable/sent` counts windows of that gap that passed the",
            "registered usable test (at least 5 of 6 transactions landed in one slot, no skipped slot).",
            "`fee-ordered` / `send-ordered` are the shares of usable windows with tau >= +0.5 / <= -0.5.", ""]
    rows = []
    for st in strata:
        for g in gaps:
            k = (st, g)
            if k not in sent_gap:
                continue
            s = summarize(by_gap.get(k, []))
            ci = f"[{f(s['ci'][0])}, {f(s['ci'][1])}]" if s["n"] else "–"
            rows.append([st, f"{g} ms", f"{sent_gap[k][1]}/{sent_gap[k][0]}", f(s["mean"]), ci,
                         pct(s["share_pos"]), pct(s["share_neg"])])
    out += table(["stratum", "send gap", "usable/sent", "mean tau (R_PRICE)", "95% interval", "fee-ordered",
                  "send-ordered"], rows)

    out += ["", "All strata together (each window one unit, validators not weighted):", ""]
    rows = []
    for g in gaps:
        taus = [t for (st, gg), v in sorted(by_gap.items()) if gg == g for t in v]
        sent = sum(v[0] for (st, gg), v in sent_gap.items() if gg == g)
        usable = sum(v[1] for (st, gg), v in sent_gap.items() if gg == g)
        s = summarize(taus)
        ci = f"[{f(s['ci'][0])}, {f(s['ci'][1])}]" if s["n"] else "–"
        rows.append([f"{g} ms", f"{usable}/{sent}", f(s["mean"]), ci, pct(s["share_pos"]), pct(s["share_neg"])])
    out += table(["send gap", "usable/sent", "mean tau (R_PRICE)", "95% interval", "fee-ordered", "send-ordered"], rows)
    out += ["", "Gaps of 60 and 120 ms mostly fail the usable test (the six transactions spread over more than one",
            "slot), so those rows are thin or empty. Nothing is imputed.", ""]

    out += ["## 2. Agave Arm C windows behind the failed positive control", "",
            "PREREGISTRATION section 7: the mean raw tau of R_RATIO_AGAVE in Arm C, pooled Agave, must lie in the 95%",
            "predictive interval of the simulator. The registered result is 0.5333 over 35 usable windows against",
            "[0.6310, 1.0000]: the control failed. Below, the same windows by run (raw tau, not normalized).", ""]
    per_run: dict[tuple[str, str], list[float]] = {}
    for w in wins:
        if w.arm == "C" and w.stratum == "Agave" and w.usable:
            per_run.setdefault((w.run_id, w.identity[:8]), []).append(
                analyze.window_scores(w, ["R_RATIO_AGAVE"])["R_RATIO_AGAVE"][1])
    rows = []
    for (run, ident), v in sorted(per_run.items()):
        s = summarize(v)
        rows.append([f"`{run}`", f"`{ident}…`", s["n"], f(s["mean"]), pct(s["share_pos"]),
                     pct(float((np.asarray(v) >= 0.999).mean()))])
    allv = [t for v in per_run.values() for t in v]
    s = summarize(allv)
    rows.append(["all", "both", s["n"], f(s["mean"]), pct(s["share_pos"]), pct(float((np.asarray(allv) >= 0.999).mean()))])
    out += table(["run", "validator", "usable windows", "mean raw tau", "tau >= 0.5", "perfect (tau = 1)"], rows)
    mean_all = float(np.mean(allv)) if allv else float("nan")
    out += ["", f"The plain mean of these {len(allv)} windows is {mean_all:.4f}; the registered value is 0.5333",
            "(`analysis/results/confirmatory_2026-11-03/positive_control.txt`). The cell means range from",
            f"{min(float(np.mean(v)) for v in per_run.values()):.2f} to {max(float(np.mean(v)) for v in per_run.values()):.2f} "
            f"with {min(len(v) for v in per_run.values())} to {max(len(v) for v in per_run.values())} windows per cell, "
            "so no run-level pattern can be read from it.", ""]

    body = "\n".join(out).rstrip("\n") + "\n"
    return body + FOOTER + hashlib.sha256(body.encode("utf-8")).hexdigest() + " -->\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(pathlib.Path(a.root).resolve())
    out = pathlib.Path(a.out)
    if a.check:
        old = out.read_bytes().replace(b"\r\n", b"\n").decode("utf-8") if out.exists() else ""
        if old != text:
            print(f"{out.name} is stale or edited by hand: regenerate with python scripts/exploratory_gap_table.py",
                  file=sys.stderr)
            return 1
        print(f"{out.name} matches its inputs")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
