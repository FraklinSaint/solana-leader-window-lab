#!/usr/bin/env python3
"""docs/VALIDATORS.md: who the 10 validators are, how each was identified, and what we measured at each.

Two tables, both generated from committed files only:
  1. Identification: the picks of `data/snapshots/selection_20261022T163227Z.json` (the selection snapshot the
     sessions used; gossip `clientId`, version string, Jito Kobe flags, our confidence level and the evidence
     list), nothing re-fetched.
  2. Measurement: per validator and arm, from `analysis/results/confirmatory_2026-11-03/results.json` (the
     registered analysis): usable/sent windows, landing rate, and the tau and verdict of the rules that answer
     "does price decide the order" (R_PRICE in arms P and C) and "does send order decide it" (R_FIFO in arm X).

    python scripts/validators_table.py            # write docs/VALIDATORS.md
    python scripts/validators_table.py --check    # exit 1 if the file differs from a regeneration

Deterministic: no wall-clock values, sorted rows, LF output, SHA-256 of the body in the last line.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SELECTION = "data/snapshots/selection_20261022T163227Z.json"
RESULTS = "analysis/results/confirmatory_2026-11-03/results.json"
OUT = ROOT / "docs" / "VALIDATORS.md"
FOOTER = "<!-- sha256: "
VERDICT = {"STRICT_RULE": "STRICT", "STRICT_RULE_LOW_SEPARATION": "STRICT (low separation)", "SOFT_RULE": "SOFT",
           "NO_RULE": "NO RULE", "INCONCLUSIVE": "inconclusive"}


def table(head: list[str], rows: list[list]) -> list[str]:
    return (["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
            + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def cell(c: dict | None, rule: str) -> str:
    """'verdict, tau' of one rule in one cell, or '–' when the cell has no usable window."""
    if not c or rule not in c["rules"]:
        return "–"
    r = c["rules"][rule]
    return f"{VERDICT.get(r['verdict'], r['verdict'])}, {r['mean_tau']:+.2f}"


def render(root: pathlib.Path) -> str:
    sel = json.loads((root / SELECTION).read_text(encoding="utf-8"))
    res = json.loads((root / RESULTS).read_text(encoding="utf-8"))
    cells = {(c["identity"], c["arm"]): c for c in res["cells"]}
    picks = sorted(sel["picked"], key=lambda p: (p["stratum"], p["identity"]))

    out = ["# Validators: identification and per-validator results", "",
           "> Generated by `python scripts/validators_table.py` from committed files (`--check` regenerates and compares).",
           f"> Identification: `{SELECTION}` (epoch {sel['epoch']}, snapshot {sel['ts']}). Results:",
           f"> `{RESULTS}` (the registered analysis). Nothing here is re-fetched or re-computed.", ""]

    out += ["## 1. How each validator was identified", "",
            "The client group is our label, built from the validator's own gossip `clientId` and version string and from",
            "Jito's Kobe validator list; `confidence` and the evidence list are what the selection step recorded. The bounty",
            "asks for client types identifiable by version string or validator-list data **at the time of measurement**: these",
            "labels were taken on the snapshot date above, four to eleven days before the sessions (2026-10-26 to",
            "2026-11-02), and were not refreshed per window. A validator that changed client or version in between would be",
            "mislabeled here; the self-reported `clientId` is not proof of what runs (README, \"What this does NOT separate\").",
            "The copies of this selection that the later sessions used (without `EvnRmnMr`) are stored as",
            "`analysis/sim/results/sessions/selection_amendment1_no_EvnRmnMr.json` (SHA-256 in `docs/AMENDMENT_1_SUPPLEMENTARY.md`);",
            "the manifest's `selection_ref` of session 5 and of round 2 names a temporary byte-identical copy of that file",
            "(`docs/AMENDMENT_2_ROUND2.md` section 3), which was removed after each session because tagged tools read the",
            "newest selection in that folder.", ""]
    rows = []
    for p in picks:
        kobe = p.get("kobe") or {}
        jito = "yes" if kobe.get("running_jito") else "no" if kobe else "not listed"
        rows.append([f"`{p['identity'][:8]}…`", f"`{p['identity']}`", p["stratum"], p["client_id"], p["version"], jito,
                     p["confidence"], "; ".join(p["evidence"]).replace("|", "/"),
                     f"{p['stake_lamports'] / 1e9:,.0f}"])
    out += table(["validator", "identity", "group", "gossip clientId", "version", "Jito (Kobe)", "confidence", "evidence",
                  "stake (SOL)"], rows)

    out += ["", "## 2. What we measured at each validator", "",
            "Verdicts are those of PREREGISTRATION §8, `tau` is the mean Kendall tau of the rule over the usable windows",
            "(+1 = the block follows the rule, -1 = the exact opposite). Arm P: fee varies, send order random. Arm C: all six",
            "transactions write-lock one account. Arm X: fee is the reverse of the send order (gap 0 to 120 ms); there",
            "`R_FIFO` is the send-order rule and `R_PRICE` is expected to come out negative if send order wins. `usable/sent` counts",
            "windows; the next column counts transactions. The failed Agave positive control weakens every verdict",
            "of the Agave family (Agave, JitoAgave, HarmonicAgave, BamAgave, Rakurai); see the README.", ""]
    rows = []
    for p in picks:
        i = p["identity"]
        us = {a: cells.get((i, a)) for a in "PCXFR"}
        sent = sum(c["windows_sent"] for c in us.values() if c)
        usable = sum(c["windows_usable"] for c in us.values() if c)
        txs = sum(sum(c["exclusions"].values()) for c in us.values() if c)
        landed = sum(c["exclusions"].get("landed", 0) for c in us.values() if c)
        rows.append([f"`{i[:8]}…`", p["stratum"], f"{usable}/{sent}",
                     f"{landed}/{txs} ({landed / txs:.0%})" if txs else "–",
                     cell(us["P"], "R_PRICE"), cell(us["C"], "R_PRICE"),
                     cell(us["X"], "R_PRICE"), cell(us["X"], "R_FIFO")])
    out += table(["validator", "group", "usable/sent windows", "transactions landed", "Arm P: price", "Arm C: price",
                  "Arm X: price", "Arm X: send order"], rows)
    out += ["", "In Arm X a negative tau of `R_PRICE` with the verdict \"inconclusive\" means the block follows the opposite of the",
            "price rule, i.e. the send order (the tests are one-sided: they can only call a rule that the data follow).", "",
            "A validator with `0/…` usable windows never had five of its six transactions land in one slot",
            "(`EvnRmnMr`: no transaction landed at all), so no rule can be tested at it.", ""]

    body = "\n".join(out).rstrip("\n") + "\n"
    return body + FOOTER + hashlib.sha256(body.encode("utf-8")).hexdigest() + " -->\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(pathlib.Path(a.root).resolve())
    out = pathlib.Path(a.out)
    if a.check:
        old = out.read_bytes().replace(b"\r\n", b"\n").decode("utf-8") if out.exists() else ""
        if old != text:
            print(f"{out.name} is stale or edited by hand: regenerate with python scripts/validators_table.py",
                  file=sys.stderr)
            return 1
        print(f"{out.name} matches its inputs")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
