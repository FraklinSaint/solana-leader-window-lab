#!/usr/bin/env python3
"""Round-2 allocation (AMENDMENT 2 of 2026-10-30, docs/AMENDMENT_2_ROUND2.md; read-only, sends nothing).

    python scripts/round2_allocation.py --write      # allocation file + dry run
    python scripts/round2_allocation.py --check      # files on disk == fresh build

Counts only (usable U and attempted A per cell, registered targets T, windows already attempted per validator and arm);
no tau, p-value, rank or verdict. Rules:
 1. cells in deficit: T - U > 0 over all measure windows so far (EvnRmnMr excluded, as in AMENDMENT 1).
 2. attempts of a cell = ceil(deficit / usable rate of the cell), rate = U / A of the cell over its own windows
    (X: all five gaps).
 3. plan_quota = plan_quota of alloc_supplementary_fullcap.json + ceil(attempts / validators) per validator in a deficit cell.
    The planner asks for quota - done per validator and arm, so the windows the fullcap file left open (5Us18hLZ: 7) stay in.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import pathlib
import sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import session_cmd as sc  # noqa: E402
import supplementary_allocation as sa  # noqa: E402

SESS = ROOT / "analysis" / "sim" / "results" / "sessions"
FULLCAP = SESS / "alloc_supplementary_fullcap.json"
SELECTION = SESS / "selection_amendment1_no_EvnRmnMr.json"
OUT = SESS / "alloc_round2.json"
DRY = ROOT / "docs" / "ROUND2_DRYRUN_FULL.txt"
MARGIN = 1.05


def plan_round2(counts: dict, tgt: dict, base: dict) -> tuple[list[dict], dict]:
    cells = sa.cell_counts(counts["rows"])
    recs = []
    plan = {s: dict(a) for s, a in base["allocation"]["plan_quota"].items()}
    extra: dict = {}
    for stratum in sorted(plan):
        for arm in sa.ARMS:
            if arm not in plan[stratum]:
                continue
            w, nv = tgt[(stratum, arm)]
            T = w * nv
            c = cells[(stratum, arm)]
            deficit = max(0, T - c["U"])
            if not deficit:
                continue
            rate = c["U"] / c["A"]
            need = math.ceil(deficit / rate)
            per = math.ceil(need / sa.n_eff(stratum, nv))
            plan[stratum][arm] += per
            extra.setdefault(stratum, {})[arm] = per
            recs.append({"stratum": stratum, "arm": arm, "T": T, "U": c["U"], "A": c["A"], "deficit": deficit,
                         "rate": rate, "need": need, "validators": sorted(c["val"]), "per_validator": per,
                         "n_validators": sa.n_eff(stratum, nv)})
    return recs, {"plan": plan, "extra": extra}


def remaining(plan: dict, sel: dict, done: dict) -> dict:
    out: dict = {}
    for p in sel["picked"]:
        i, s = p["identity"], p["stratum"]
        for arm, q in plan.get(s, {}).items():
            out[(i[:8], s, arm)] = max(q - done.get((i, arm), 0), 0)
    return out


def build_file(base: dict, res: dict, counts: dict) -> dict:
    return {
        "label": "ROUND-2 ALLOCATION FILE (AMENDMENT 2, 2026-10-30; scripts/round2_allocation.py)",
        "source": {"file": "alloc_supplementary_fullcap.json", "targets": "alloc_v2.json scenario calibrated",
                   "counts": f"usable and attempted windows of purpose measure, sessions 1 to 5, {counts['verify_file']}"},
        "session": "round2", "sessions": 4, "cumulative_share": "4/4 + supplementary + round 2", "cap": "full",
        "rounding": "plan_quota = plan_quota of alloc_supplementary_fullcap.json + ceil(attempts of the cell / validators) per validator "
                    "in a cell in deficit; attempts = ceil(deficit / usable rate of the cell)",
        "dropped_strata": base["dropped_strata"], "excluded_validators": base["excluded_validators"],
        "allocation": {"n": base["allocation"]["n"], "usable_rate": base["allocation"]["usable_rate"],
                       "spend_per_window_lamports": base["allocation"]["spend_per_window_lamports"], "plan_quota": res["plan"]},
        "full_plan_quota": res["plan"],
        "round2": {"quota_per_validator": res["extra"],
                   "note": "excluded_validators and round2 are NOT read by the sender (planner.rs); the selection copy without EvnRmnMr is"},
    }


def dry_text(counts: dict, recs: list[dict], res: dict, sel: dict, base: dict, data: pathlib.Path, sup: dict, epochs: list, sha: str) -> str:
    spend = base["allocation"]["spend_per_window_lamports"]
    done = sc.attempted(data)
    rem = remaining(res["plan"], sel, done)
    rem_old = remaining(base["allocation"]["plan_quota"], sel, done)
    L: list[str] = []
    A = L.append
    A("ROUND 2 DRY RUN (AMENDMENT 2 of 2026-10-30; read-only; counts only; no tau/p/verdict; nothing sent)")
    A(f"generated by scripts/round2_allocation.py (SHA-256 {sha}); counts from {counts['verify_file']} ({counts['windows']} measure windows, sessions 1 to 5)")
    A("")
    A("== 1. Cells below the registered target T (U usable, A attempted, rate U/A of the cell; X over all five gaps; EvnRmnMr excluded)")
    A("stratum             arm   T    U    A  deficit   rate   attempts=ceil(D/rate)  validators  per-validator  cost(lamports)")
    tot_att = 0
    for r in recs:
        tot_att += r["need"]
        A(f"{r['stratum']:<19} {r['arm']}  {r['T']:>3}  {r['U']:>3}  {r['A']:>3}  {r['deficit']:>6}  {r['rate']:.3f}  {r['need']:>14}  {r['n_validators']:>10}  {r['per_validator']:>13}  {r['need'] * spend[r['arm']]:>12,.0f}")
    A(f"deficit cells: {len(recs)} cells, deficit {sum(r['deficit'] for r in recs)} usable windows, {tot_att} attempts, {sum(r['need'] * spend[r['arm']] for r in recs):,.0f} lamports")
    A("")
    A("== 2. Windows still open in the file (plan_quota - windows attempted, per validator x arm)")
    left_old = sum(rem_old.values())
    A("  alloc_supplementary_fullcap.json alone (what session 5 left): " + "; ".join(f"{k[0]} {k[2]} {v}" for k, v in sorted(rem_old.items()) if v) + f"  = {left_old} windows")
    A("  alloc_round2.json (the file of this round):")
    per_val: Counter = Counter()
    cost = 0
    for (v, s, arm), n in sorted(rem.items()):
        per_val[v] += n
        cost += n * int(spend[arm])
    for (v, s, arm), n in sorted(rem.items()):
        if n:
            A(f"    {v}  {s:<19} {arm}  {n:>3}  (of which left open by fullcap {rem_old[(v, s, arm)]})")
    tot = sum(per_val.values())
    A(f"  TOTAL: {tot} windows, {cost:,} lamports; with the 1.05 margin {math.ceil(cost * MARGIN):,}")
    A(f"  EvnRmnMr is not in the selection copy: windows planned for it {sum(1 for k in rem if k[0] == 'EvnRmnMr')}")
    A(f"  order said 108 = {tot_att} deficit attempts + {left_old} left open for 5Us18hLZ = {tot_att + left_old}; this file: {tot}.")
    diff = [r for r in recs if r["n_validators"] * r["per_validator"] != r["need"]]
    A("  difference = whole per-validator quotas (every validator of a pool gets the same quota): " +
      ("; ".join(f"{r['stratum']} {r['arm']}: {r['n_validators']} x {r['per_validator']} = {r['n_validators'] * r['per_validator']} for {r['need']} attempts" for r in diff) or "none") + ".")
    A("  overlap not subtracted: the 2 windows of Agave X left open for 5Us18hLZ also count toward the Agave X deficit.")
    A("")
    A("== 3. Windows per validator, supply (leader windows an hour, saved mainnet epochs " + str(epochs) + ") and hours at supply")
    hs = sorted(((n / sup[v], v, n) for v, n in per_val.items() if n), reverse=True)
    for h, v, n in hs:
        A(f"    {v}  {n:>3} windows  supply {sup[v]:>6.1f}/h  -> {h:.2f} h")
    A(f"  bottleneck by supply: {hs[0][1]}; at the sender rate {sa.SENDER_RATE:.0f}/h (session 4): {tot / sa.SENDER_RATE:.2f} h; at 27.3/h (session 5, paced over 9 h): {tot / 27.3:.2f} h")
    A("  X gaps are not restricted (no code change): the planner rotates 0, 10, 25, 60, 120 ms, so about 40% of the X windows fall at 60/120 ms, where the usable rate is low.")
    A("")
    A("== 4. Budget (lamports)")
    com = sc.committed(data)
    cap = math.ceil(cost * MARGIN)
    A(f"  confirmatory: committed (measure fees paid + open reservations) {com:,} + round 2 {cost:,} = {com + cost:,} <= 38,000,000 (margin {38_000_000 - com - cost:,}); with cap {cap:,}: {com + cap:,} (margin {38_000_000 - com - cap:,})")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--data", default=str(ROOT / "data"))
    a = ap.parse_args(argv)
    data = pathlib.Path(a.data)
    alloc = json.loads((ROOT / "analysis/sim/results/alloc_v2.json").read_text(encoding="utf-8"))
    base = json.loads(FULLCAP.read_text(encoding="utf-8"))
    sel = json.loads(SELECTION.read_text(encoding="utf-8"))
    counts = sa.load_counts(data)
    recs, res = plan_round2(counts, sa.targets(alloc), base)
    sup, epochs = sa.supply(data)
    sha = hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest()
    out = {OUT: sa.dump(build_file(base, res, counts)),
           DRY: dry_text(counts, recs, res, sel, base, data, sup, epochs, sha).encode("utf-8")}
    bad = 0
    for p, b in out.items():
        if a.check:
            ok = p.exists() and p.read_bytes() == b
            print(("ok       " if ok else "DIFFERS  ") + str(p))
            bad += 0 if ok else 1
        else:
            p.write_bytes(b)
            print(f"wrote {p}  sha256 {hashlib.sha256(b).hexdigest()}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
